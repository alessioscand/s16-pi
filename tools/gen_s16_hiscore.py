#!/usr/bin/env python3
"""s16-pi: build core/s16_hiscore.inc from MAME's hiscore plugin data.

    python3 tools/gen_s16_hiscore.py <mame>/plugins/hiscore/hiscore.dat \\
            core/s16_games.inc > core/s16_hiscore.inc

Keeps the entries of the sets in s16_games.inc, as MAME reads them: a set
without its own entry has no hiscore saving (no fall-back to the parent).
Only main CPU program-space rows are expected; @delay and prefill are refused.
(From m92-pi's gen_m92_hiscore.py.)
"""
import re, sys

dat_path, games_path = sys.argv[1], sys.argv[2]
names = [s for s, _ in re.findall(r'\{\s*"([a-z0-9]+)",\s*"([a-z0-9]*)",\s*"', open(games_path).read())]

entries = {}
pending, rows = [], []

def flush():
	global pending, rows
	if pending and rows:
		for n in pending:
			entries.setdefault(n, list(rows))
	pending, rows = [], []

for raw in open(dat_path, encoding='latin-1'):
	line = re.sub(r'[ \t\r\n]*;.*$', '', raw).strip()
	if not line:
		continue
	if line.startswith('@'):
		rows.append(line)
	elif re.match(r'^[a-z0-9_,]+:$', line):
		if rows:
			flush()
		pending.append(line[:-1])
flush()

out = ['// Generated by tools/gen_s16_hiscore.py from MAME plugins/hiscore/hiscore.dat',
       '// (MAME hiscore plugin data, Leezer and contributors). Do not edit by hand.', '']
table = []
for n in names:
	if n not in entries:
		continue
	parsed = []
	for r in entries[n]:
		if r.startswith('@delay'):
			sys.exit(f'{n}: @delay not supported')
		f = r[1:].split(',')
		if f[0] != ':maincpu' or f[1] != 'program':
			sys.exit(f'{n}: {r}: only :maincpu,program')
		if len(f) > 6 and f[6]:
			sys.exit(f'{n}: {r}: prefill not supported')
		parsed.append(tuple(int(x, 16) for x in f[2:6]))
	out.append(f'static const TS16HiRow hirows_{n}[] =')
	out.append('{')
	for addr, size, first, last in parsed:
		out.append(f'\t{{0x{addr:06x}, 0x{size:03x}, 0x{first:02x}, 0x{last:02x}}},')
	out.append('};')
	table.append((n, len(parsed)))

out += ['', 'static const TS16Hiscore s_Hiscores[] =', '{']
for n, k in table:
	out.append(f'\t{{"{n}", hirows_{n}, {k}}},')
out.append('};')
print('\n'.join(out))
missing = [n for n in names if n not in entries]
print(f'{len(table)} sets with hiscores; none for: {" ".join(missing)}', file=sys.stderr)
